/** `annon init` without --agent: validate the selected backup secret or create the default. */
import { randomBytes } from 'node:crypto';
import { constants } from 'node:fs';
import { link, mkdir, open, unlink } from 'node:fs/promises';
import { basename, dirname, join } from 'node:path';
import { newBackupSecret } from '../pay/backup.js';
import { hex } from '../settle-near/codec.js';
import { agentPolicy } from './agent.js';
import {
  type BackupSecretSource,
  checkAppDirectory,
  defaultBackupSecretPath,
  findBackupSecret,
  readDefaultSecret,
  unsafeDefault,
} from './backup-secret.js';
import type { Input } from './cli.js';
import { AdapterError } from './errors.js';
import { assertNoSavedState } from './saved-state.js';
import { syncDir } from './sync-dir.js';
import type { Environment } from './wallets.js';

const setupError = (message: string) => new AdapterError('backup_secret_required', message, 2);

/**
 * Writes the secret to an exclusive owner-only temporary file, then publishes it with link(),
 * which never replaces an existing path (rename() would). Returns false when another
 * invocation already published one; its file is validated and the generated bytes are dropped.
 */
async function createDefaultSecret(path: string): Promise<boolean> {
  const dir = dirname(path);
  // Missing parents are created 0700; an existing directory is only checked, never changed.
  await mkdir(dir, { recursive: true, mode: 0o700 });
  await checkAppDirectory(dir);
  const temp = join(dir, `.${basename(path)}.${randomBytes(8).toString('hex')}.tmp`);
  const handle = await open(temp, constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL, 0o600);
  let published: boolean;
  try {
    const secret = newBackupSecret();
    try {
      await handle.writeFile(`${hex(secret).slice(2)}\n`);
      await handle.sync();
    } finally {
      secret.fill(0);
      await handle.close();
    }
    published = await link(temp, path).then(
      () => true,
      (error: NodeJS.ErrnoException) => {
        if (error.code === 'EEXIST') return false;
        throw error;
      },
    );
  } finally {
    await unlink(temp).catch(() => {});
  }
  if (!published) {
    if (!(await readDefaultSecret(path))) throw unsafeDefault();
    return false;
  }
  try {
    await syncDir(dir);
  } catch {
    // The published file stays: deleting a secret is never cleanup. A rerun validates it.
    throw setupError(
      'The backup secret file was created but its directory could not be synced. Rerun annon init to validate it.',
    );
  }
  return true;
}

const printable = (path: string) => (/\p{Cc}/u.test(path) ? JSON.stringify(path) : path);
const notice = (path: string) =>
  [
    `Created a plaintext backup-secret file with owner-only permissions: ${printable(path)}`,
    'Back up this file separately in protected storage. Losing it loses access to local saved purchase and sell records and backup files. Wallet-based purchase recovery through the contract still works.',
    'Copy the file without displaying its contents. To restore it, select the copied file with ANNON_BACKUP_SECRET_FILE.',
  ].join('\n');
const result = (source: BackupSecretSource, path: string | undefined, created: boolean) => ({
  configured: true,
  backupSecret: { source, ...(path ? { path } : {}), created },
});

/**
 * The agent-policy check for bare init. A config that cannot be read must stop setup with a
 * setup error, not a generic failure; policy refusals stay as they are.
 */
export async function initPolicy(o: Input, env: Environment, forced?: boolean) {
  try {
    return await agentPolicy(o, env, forced);
  } catch (error) {
    if (error instanceof AdapterError) throw error;
    throw setupError(
      'The Annon config could not be read to check agent policy. Fix or restore it before running annon init.',
    );
  }
}

/** Never writes an explicit source; creates the default only when no secret exists at all. */
export async function initBackupSecret(
  o: Partial<Input>,
  env: Environment,
  notify?: (message: string) => void,
): Promise<Record<string, unknown>> {
  const found = await findBackupSecret(o, env);
  if (found) return result(found.source, found.path, false);
  await assertNoSavedState(o, env);
  const path = defaultBackupSecretPath();
  let created: boolean;
  try {
    created = await createDefaultSecret(path);
  } catch (error) {
    if (error instanceof AdapterError) throw error;
    throw setupError(
      'The backup secret file could not be created. Nothing else was tried; fix ~/.config/annon and rerun annon init.',
    );
  }
  if (created) notify?.(notice(path));
  return result('default-file', path, created);
}
